"""Behavior checks based on README's geometry, background, and CLI contracts."""
import importlib.util
import math
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

from PIL import Image, ImageDraw, PngImagePlugin

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('circle_img', ROOT / 'circle-img.py')
app = importlib.util.module_from_spec(spec)
spec.loader.exec_module(app)


def fixture(size=(17, 13), box=(1, 2, 14, 10), rgba=(30, 120, 240, 255)):
    image = Image.new('RGBA', size)
    ImageDraw.Draw(image).rectangle(box, fill=rgba)
    # Independently establish the support and colors generated by this fixture.
    expected_count = (box[2] - box[0] + 1) * (box[3] - box[1] + 1)
    assert sum(a > 0 for a in image.getchannel('A').get_flattened_data()) == expected_count
    assert image.getpixel((box[0], box[1])) == rgba
    assert image.getchannel('A').getbbox() == (box[0], box[1], box[2] + 1, box[3] + 1)
    return image


class GeometryTests(unittest.TestCase):
    def assert_contained(self, layer, margin):
        side = layer.width
        self.assertEqual(side, layer.height)
        count = 0
        for y in range(side):
            for x in range(side):
                if layer.getpixel((x, y))[3]:
                    count += 1
                    for dx, dy in ((0, 0), (1, 0), (0, 1), (1, 1)):
                        self.assertLessEqual(math.hypot(x + dx - side / 2, y + dy - side / 2)
                                             + margin, side / 2)
        self.assertGreater(count, 0)

    def test_shapes_and_margins(self):
        shapes = [fixture(), fixture((8, 8), (0, 0, 7, 7)),
                  fixture((9, 4), (0, 0, 8, 3)), fixture((1, 1), (0, 0, 0, 0)),
                  fixture((3, 15), (1, 0, 1, 14), (11, 22, 33, 1))]
        for source in shapes:
            for margin in (0, 1, 12):
                with self.subTest(size=source.size, margin=margin):
                    output, layer, offset = app.render(source, (0, 0, 0, 0), margin)
                    self.assert_contained(layer, margin)
                    self.assertGreaterEqual(output.width, max(source.size))
                    crop = source.crop(source.getchannel('A').getbbox())
                    x, y = offset
                    self.assertEqual(layer.crop((x, y, x + crop.width, y + crop.height)).tobytes(), crop.tobytes())
                    self.assertEqual(output.tobytes(), layer.tobytes())

    def test_shape_aware_padding(self):
        diamond = Image.new('RGBA', (21, 21))
        for y in range(21):
            for x in range(21):
                if abs(x - 10) + abs(y - 10) <= 10:
                    diamond.putpixel((x, y), (10, 20, 30, 255))
        self.assertEqual(diamond.getchannel('A').getbbox(), (0, 0, 21, 21))
        self.assertEqual(sum(a > 0 for a in diamond.getchannel('A').get_flattened_data()), 221)
        square = Image.new('RGBA', (21, 21), 'red')
        out, layer, _ = app.render(diamond, (255, 255, 255, 255), 0)
        self.assert_contained(layer, 0)
        self.assertLess(out.width, app.render(square, (255, 255, 255, 255), 0)[0].width)

    def test_composite_known_values(self):
        source = fixture((3, 3), (1, 1, 1, 1), (100, 50, 0, 128))
        result, _, offset = app.render(source, (255, 255, 255, 255), 0)
        self.assertEqual(result.getpixel(offset), (177, 152, 127, 255))
        self.assertEqual(result.getpixel((0, 0)), (255, 255, 255, 255))

    def test_empty(self):
        with self.assertRaisesRegex(ValueError, 'no foreground'):
            app.render(Image.new('RGBA', (4, 4)), (255, 255, 255, 255), 0)


class BackgroundTests(unittest.TestCase):
    def test_existing_alpha_is_exact(self):
        source = fixture(rgba=(10, 20, 30, 1))
        result, method = app.foreground(source)
        self.assertEqual(method, 'existing alpha')
        self.assertEqual(result.tobytes(), source.tobytes())

    def test_flood_fill_preserves_enclosed_white(self):
        source = Image.new('RGBA', (7, 7), 'white')
        ImageDraw.Draw(source).rectangle((1, 1, 5, 5), outline='red', width=1)
        self.assertEqual(sum(p[:3] == (255, 0, 0) for p in source.get_flattened_data()), 16)
        result, _ = app.foreground(source)
        self.assertEqual(result.getpixel((0, 0))[3], 0)
        self.assertEqual(result.getpixel((3, 3)), (255, 255, 255, 255))
        self.assertEqual(result.getpixel((1, 1)), (255, 0, 0, 255))
        self.assertEqual(sum(a > 0 for a in result.getchannel('A').get_flattened_data()), 25)

    def test_tolerance_and_explicit_color(self):
        source = Image.new('RGBA', (5, 5), (250, 250, 250, 255))
        source.putpixel((2, 2), (20, 30, 40, 255))
        result, _ = app.foreground(source, 'white', 5)
        self.assertEqual(result.getchannel('A').getbbox(), (2, 2, 3, 3))
        unchanged, _ = app.foreground(source, 'white', 4)
        self.assertEqual(unchanged.tobytes(), source.tobytes())

    def test_ambiguous_background(self):
        source = Image.new('RGBA', (5, 5), 'white')
        ImageDraw.Draw(source).rectangle((0, 0, 2, 4), fill='blue')
        with self.assertRaisesRegex(ValueError, 'ambiguous'):
            app.foreground(source)

    def test_mask_multiplies_original_alpha(self):
        source = Image.new('RGBA', (2, 1), (20, 30, 40, 128))
        mask = Image.new('L', (2, 1), 128)
        mask.putpixel((0, 0), 0)
        result, _ = app.foreground(source, mask=mask)
        self.assertEqual(result.getpixel((0, 0))[3], 0)
        self.assertEqual(result.getpixel((1, 0)), (20, 30, 40, 64))
        with self.assertRaisesRegex(ValueError, 'dimensions'):
            app.foreground(source, mask=Image.new('L', (1, 1)))

    def test_binary_mask(self):
        source = Image.new('RGBA', (2, 1), (20, 30, 40, 128))
        mask = Image.new('1', (2, 1), 1)
        mask.putpixel((0, 0), 0)
        self.assertEqual(list(mask.get_flattened_data()), [0, 1])
        result, _ = app.foreground(source, mask=mask)
        self.assertEqual(result.getpixel((0, 0))[3], 0)
        self.assertEqual(result.getpixel((1, 0)), (20, 30, 40, 128))


class CLITests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.directory = Path(self.temp.name)
        self.source = self.directory / 'logo.png'
        fixture().save(self.source)

    def cli(self, *args, success=True):
        result = subprocess.run([sys.executable, str(ROOT / 'circle-img.py'), '-i', str(self.source), *map(str, args)],
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0 if success else 1, result.stdout + result.stderr)
        return result


    def test_batch_directory_and_previews(self):
        second = self.directory / 'second image.png'
        fixture(rgba=(200, 10, 30, 255)).save(second)
        destination = self.directory / 'exports'
        destination.mkdir()
        self.cli(second, '-o', destination, '--preview')
        self.assertEqual({p.name for p in destination.iterdir()},
                         {'logo.png', 'logo-preview.png', 'second image.png', 'second image-preview.png'})
        with Image.open(destination / 'second image.png') as result:
            self.assertEqual(result.getpixel((result.width // 2, result.height // 2)), (200, 10, 30, 255))

    def test_batch_default_outputs_and_repeated_input(self):
        second = self.directory / 'second.png'
        fixture().save(second)
        self.cli('-i', second)
        self.assertTrue((self.directory / 'logo-circle.png').is_file())
        self.assertTrue((self.directory / 'second-circle.png').is_file())

    def test_batch_requires_directory_for_output(self):
        second = self.directory / 'second.png'
        fixture().save(second)
        result = self.cli(second, '-o', self.directory / 'combined.png', success=False)
        self.assertIn('multiple inputs require an existing output directory', result.stderr)
        self.assertFalse((self.directory / 'combined.png').exists())
        self.assertFalse((self.directory / 'logo-circle.png').exists())

    def test_batch_continues_after_ambiguous_input(self):
        bad = self.directory / 'ambiguous.png'
        source = Image.new('RGBA', (5, 5), 'white')
        ImageDraw.Draw(source).rectangle((0, 0, 2, 4), fill='blue')
        self.assertEqual(source.getpixel((0, 0)), (0, 0, 255, 255))
        self.assertEqual(source.getpixel((4, 0)), (255, 255, 255, 255))
        source.save(bad)
        original_good = self.source
        self.source = bad
        result = self.cli(original_good, success=False)
        self.assertIn(str(bad), result.stderr)
        self.assertIn('ambiguous background', result.stderr)
        self.assertTrue((self.directory / 'logo-circle.png').is_file())
        self.assertFalse((self.directory / 'ambiguous-circle.png').exists())

    def test_batch_continues_after_existing_output_and_can_overwrite(self):
        second = self.directory / 'second.png'
        fixture().save(second)
        target = self.directory / 'logo-circle.png'
        target.write_bytes(b'keep')
        result = self.cli(second, success=False)
        self.assertIn(str(self.source), result.stderr)
        self.assertEqual(target.read_bytes(), b'keep')
        self.assertTrue((self.directory / 'second-circle.png').is_file())
        self.cli(second, '-O')
        with Image.open(target) as image:
            self.assertEqual(image.format, 'PNG')

    def test_batch_output_collisions_abort_before_writing(self):
        folder = self.directory / 'other'
        folder.mkdir()
        second = folder / 'logo.png'
        fixture().save(second)
        destination = self.directory / 'exports'
        destination.mkdir()
        result = self.cli(second, '-o', destination, '-O', success=False)
        self.assertIn('output collision', result.stderr)
        self.assertEqual(list(destination.iterdir()), [])

    def test_batch_preview_collision_aborts_before_writing(self):
        second = self.directory / 'logo-preview.png'
        fixture().save(second)
        destination = self.directory / 'exports'
        destination.mkdir()
        result = self.cli(second, '-o', destination, '--preview', '-O', success=False)
        self.assertIn('output collision', result.stderr)
        self.assertEqual(list(destination.iterdir()), [])

    def test_batch_protects_every_input_before_writing(self):
        second = self.directory / 'logo-circle.png'
        fixture().save(second)
        before = second.read_bytes()
        result = self.cli(second, '-O', success=False)
        self.assertIn('output cannot replace the input or mask', result.stderr)
        self.assertEqual(second.read_bytes(), before)
        self.assertFalse((self.directory / 'logo-circle-circle.png').exists())

    def test_batch_shell_glob(self):
        second = self.directory / 'second image.png'
        fixture().save(second)
        destination = self.directory / 'exports'
        destination.mkdir()
        # The real shell expands the wildcard, keeping paths with spaces intact.
        result = subprocess.run(['bash', '-c', '"$1" "$2" -i ./*.png -o exports',
                                 'batch-test', sys.executable, str(ROOT / 'circle-img.py')],
                                cwd=self.directory, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual({p.name for p in destination.iterdir()}, {'logo.png', 'second image.png'})

    def test_default_and_preview(self):
        self.cli('--preview', '--margin', '3')
        with Image.open(self.directory / 'logo-circle.png') as output:
            self.assertEqual(output.format, 'PNG')
            self.assertEqual(output.width, output.height)
            self.assertEqual(output.getpixel((0, 0)), (255, 255, 255, 255))
        with Image.open(self.directory / 'logo-circle-preview.png') as preview:
            self.assertEqual(preview.getpixel((0, 0))[3], 0)
            self.assertEqual(preview.getpixel((preview.width // 2, preview.height // 2))[3], 255)

    def test_output_directory_preserves_filename_and_preview(self):
        destination = self.directory / 'export folder'
        destination.mkdir()
        self.assertTrue(destination.is_dir())
        self.cli('-o', destination, '--preview')
        self.assertEqual({p.name for p in destination.iterdir()}, {'logo.png', 'logo-preview.png'})
        with Image.open(destination / 'logo.png') as result:
            self.assertEqual(result.format, 'PNG')
            self.assertEqual(result.width, result.height)
        with Image.open(destination / 'logo-preview.png') as result:
            self.assertEqual(result.getpixel((0, 0))[3], 0)

    def test_output_directory_converts_jpeg_extension(self):
        self.source = self.directory / 'photo.jpg'
        image = Image.new('RGB', (17, 13), 'white')
        ImageDraw.Draw(image).rectangle((4, 4, 12, 8), fill='blue')
        image.save(self.source)
        with Image.open(self.source) as saved:
            self.assertEqual(saved.format, 'JPEG')
            self.assertEqual(saved.size, (17, 13))
            self.assertNotEqual(saved.getpixel((8, 6)), saved.getpixel((0, 0)))
        destination = self.directory / 'exports'
        destination.mkdir()
        self.cli('-o', destination, '--source-background', 'white')
        self.assertEqual({p.name for p in destination.iterdir()}, {'photo.png'})
        with Image.open(destination / 'photo.png') as result:
            self.assertEqual(result.format, 'PNG')

    def test_output_directory_with_png_suffix_and_uppercase_input(self):
        renamed = self.source.with_name('Logo.PNG')
        self.source.rename(renamed)
        self.source = renamed
        destination = self.directory / 'exports.png'
        destination.mkdir()
        self.cli('-o', destination)
        self.assertTrue((destination / 'Logo.PNG').is_file())

    def test_output_directory_collision_and_overwrite(self):
        destination = self.directory / 'exports'
        destination.mkdir()
        target = destination / self.source.name
        target.write_bytes(b'keep existing output')
        result = self.cli('-o', destination, success=False)
        self.assertIn('output exists', result.stderr)
        self.assertEqual(target.read_bytes(), b'keep existing output')
        self.cli('-o', destination, '-O')
        with Image.open(target) as result:
            self.assertEqual(result.format, 'PNG')

    def test_output_directory_protects_input(self):
        original = self.source.read_bytes()
        result = self.cli('-o', self.source.parent, '-O', success=False)
        self.assertIn('output cannot replace the input or mask', result.stderr)
        self.assertEqual(self.source.read_bytes(), original)

    def test_output_directory_preview_collision(self):
        destination = self.directory / 'exports'
        destination.mkdir()
        preview = destination / 'logo-preview.png'
        preview.write_bytes(b'keep preview')
        result = self.cli('-o', destination, '--preview', success=False)
        self.assertIn('output exists', result.stderr)
        self.assertEqual(preview.read_bytes(), b'keep preview')
        self.assertFalse((destination / 'logo.png').exists())

    def test_explicit_output_filename(self):
        destination = self.directory / 'custom.png'
        self.cli('-o', destination)
        self.assertTrue(destination.is_file())
        self.assertFalse((self.directory / 'logo-circle.png').exists())

    def test_dependency_fallback_without_activation(self):
        # -S removes site packages; verify this really models missing Pillow.
        interpreter = sys._base_executable
        probe = subprocess.run([interpreter, '-S', '-c', 'import PIL'], capture_output=True, text=True)
        self.assertNotEqual(probe.returncode, 0)
        self.assertIn("No module named 'PIL'", probe.stderr)
        result = subprocess.run([interpreter, '-S', str(ROOT / 'circle-img.py'),
                                 '-i', str(self.source), '--margin', '5'],
                                cwd=self.directory, capture_output=True, text=True, timeout=15)
        self.assertEqual(result.returncode, 0, result.stderr)
        with Image.open(self.directory / 'logo-circle.png') as output:
            self.assertEqual(output.format, 'PNG')
            self.assertGreater(output.width, 17)

    def test_missing_dependencies_explain_setup(self):
        script = self.directory / 'circle-img.py'
        script.write_bytes((ROOT / 'circle-img.py').read_bytes())
        result = subprocess.run([sys._base_executable, '-S', str(script), '--help'],
                                capture_output=True, text=True, timeout=15)
        self.assertEqual(result.returncode, 1)
        self.assertIn('Pillow is not installed', result.stderr)
        self.assertIn('pip install -r requirements.txt', result.stderr)
        self.assertNotIn('Traceback', result.stderr)

    def test_overwrite_protection(self):
        self.cli()
        target = self.directory / 'logo-circle.png'
        before = target.read_bytes()
        self.assertIn('output exists', self.cli(success=False).stderr)
        self.assertEqual(target.read_bytes(), before)
        self.cli('--overwrite', '--background', 'transparent')
        self.assertNotEqual(target.read_bytes(), before)
        self.cli('-O')
        with Image.open(target) as output:
            self.assertEqual(output.getpixel((0, 0)), (255, 255, 255, 255))
        original = self.source.read_bytes()
        self.cli('-o', self.source, '--overwrite', success=False)
        self.assertEqual(self.source.read_bytes(), original)
        alias = self.directory / 'alias.png'
        alias.hardlink_to(self.source)
        self.cli('-o', alias, '--overwrite', success=False)
        self.assertEqual(self.source.read_bytes(), original)

    def test_preview_collision_is_checked_before_output(self):
        target = self.directory / 'logo-circle-preview.png'
        target.write_bytes(b'keep')
        self.cli('--preview', success=False)
        self.assertEqual(target.read_bytes(), b'keep')
        self.assertFalse((self.directory / 'logo-circle.png').exists())

    def test_invalid_arguments(self):
        for args in [('--margin', '-1'), ('--tolerance', '256'), ('--background', 'nonsense'),
                     ('-o', 'bad.jpg'), ('-o', self.directory / 'missing' / 'out.png')]:
            with self.subTest(args=args):
                self.cli(*args, success=False)

    def test_mask_cli(self):
        mask = self.directory / 'mask.png'
        Image.new('L', (17, 13), 255).save(mask)
        self.cli('--mask', mask, '--background', 'transparent')
        self.cli('--mask', mask, '-o', mask, '--overwrite', success=False)
        self.cli('--mask', mask, '--tolerance', '2', success=False)

    def test_png_metadata(self):
        info = PngImagePlugin.PngInfo()
        info.add(b'sRGB', b'\x00')
        info.add(b'gAMA', (45455).to_bytes(4, 'big'))
        fixture().save(self.source, pnginfo=info, dpi=(144, 144))
        self.cli()
        with Image.open(self.directory / 'logo-circle.png') as result:
            self.assertEqual(result.info['srgb'], 0)
            self.assertEqual(result.info['gamma'], .45455)
            self.assertAlmostEqual(result.info['dpi'][0], 144, delta=.02)

    def test_orientation(self):
        image = fixture((10, 5), (1, 1, 3, 3))
        exif = Image.Exif()
        exif[274] = 6
        image.save(self.source, exif=exif)
        result, _ = app.load_image(self.source)
        self.assertEqual(result.size, (5, 10))
        self.assertEqual(result.getchannel('A').getbbox(), (1, 1, 4, 4))

    def test_high_depth_and_animation_rejected(self):
        Image.new('I;16', (3, 3), 1000).save(self.source)
        self.assertIn('16-bit', self.cli(success=False).stderr)
        Image.new('RGB', (3, 3), 'red').save(self.source, format='GIF', save_all=True,
                                           append_images=[Image.new('RGB', (3, 3), 'blue')])
        self.assertIn('multi-frame', self.cli(success=False).stderr)


